-- Run once in Supabase SQL Editor before deploying this Preview version.
-- Additive: does not remove previous shift records.
create table if not exists public.gym_coach_class_checkins (
 id bigint generated by default as identity primary key,
 coach_id bigint not null references public.gym_coaches(id),
 work_date date not null,
 kind text not null check (kind in ('regular','private')),
 class_session_id bigint references public.class_sessions(id),
 class_name text not null,
 scheduled_start_time time,
 checked_in_at timestamptz not null default now(),
 constraint regular_requires_session check ((kind='regular' and class_session_id is not null) or (kind='private' and class_session_id is null))
);
create unique index if not exists coach_one_checkin_per_regular_class on public.gym_coach_class_checkins(coach_id,class_session_id) where class_session_id is not null;
create index if not exists coach_class_checkin_month_idx on public.gym_coach_class_checkins(coach_id,work_date);
alter table public.gym_coach_class_checkins enable row level security;
revoke all on public.gym_coach_class_checkins from anon, authenticated;
